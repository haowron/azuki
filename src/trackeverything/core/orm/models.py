"""core の 14 表の ORM モデル — プロジェクト唯一の ORM。

core の表を定義する。不使用(データ保持)の購読表は queue/models.py が同じ Base.metadata に登録する。
モデルは migration 適用後の schema と完全に一致する定義の正本でなければならない。
型・既定値・CHECK・外部参照・索引を変えるときは、同じ変更で Alembic の revision を作る。
表を削除するときは class を除き、drop を revision に手で書く(``alembic/env.py`` の
``include_object`` がモデルにない表を比較から外すため、autogenerate は drop を出さない)。

各 Store はこのモデルを通してだけ表へ読み書きする。SQL 文字列を
Store 側に持たせない。列の宣言順は配備表の列順と同じ並びで保つ。

Naming invariant: "Track / Tracking" everywhere, never "trace".
"""

from __future__ import annotations

from datetime import datetime
from typing import Any

from sqlalchemy import (
    BigInteger,
    Boolean,
    CheckConstraint,
    DateTime,
    Double,
    ForeignKey,
    Identity,
    Index,
    Integer,
    Text,
    UniqueConstraint,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column


class Base(DeclarativeBase):
    """全アプリケーション表の共通基底。schema の作成・変更は Alembic が所有する。"""


class ExecutionReceipt(Base):
    """``execution_receipt`` — 不使用(データ保持)。旧 queue の成功証跡。ORM 定義は ``alembic check`` のためだけに残す。"""

    __tablename__ = "execution_receipt"
    namespace: Mapped[str] = mapped_column(Text, primary_key=True)
    message_id: Mapped[str] = mapped_column(Text, primary_key=True)
    attempts: Mapped[int] = mapped_column(Integer, server_default=text("0"))
    state: Mapped[str] = mapped_column(Text, server_default=text("'pending'"))
    active_attempt_id: Mapped[str | None] = mapped_column(Text)
    session_id: Mapped[str | None] = mapped_column(Text)
    session_bound: Mapped[bool] = mapped_column(Boolean, server_default=text("FALSE"))
    run_id: Mapped[str | None] = mapped_column(Text)
    targets: Mapped[list[str]] = mapped_column(JSONB, server_default=text("'[]'::jsonb"))
    error: Mapped[str | None] = mapped_column(Text)
    deadline: Mapped[float | None] = mapped_column(Double)
    event_run_id: Mapped[str | None] = mapped_column(Text)
    forwarded: Mapped[bool] = mapped_column(Boolean, server_default=text("FALSE"))
    __table_args__ = (CheckConstraint("attempts >= 0 AND attempts <= 3", name="ck_execution_receipt_attempts"),)


class ExecutionAttempt(Base):
    """``execution_attempt`` — 不使用(データ保持)。旧 queue の試行記録。"""

    __tablename__ = "execution_attempt"
    id: Mapped[str] = mapped_column(Text, primary_key=True)
    namespace: Mapped[str] = mapped_column(Text)
    message_id: Mapped[str] = mapped_column(Text)
    token: Mapped[str] = mapped_column(Text)
    number: Mapped[int] = mapped_column(Integer)
    started_at: Mapped[float] = mapped_column(Double)
    deadline: Mapped[float] = mapped_column(Double)
    finished_at: Mapped[float | None] = mapped_column(Double)
    status: Mapped[str] = mapped_column(Text, server_default=text("'running'"))
    run_id: Mapped[str | None] = mapped_column(Text)
    session_id: Mapped[str | None] = mapped_column(Text)
    error: Mapped[str | None] = mapped_column(Text)
    __table_args__ = (
        UniqueConstraint("namespace", "message_id", "token", name="uq_execution_attempt_delivery"),
        Index("idx_execution_attempt_message", "namespace", "message_id", "number"),
    )


class ExecutionChild(Base):
    """``execution_child`` — 不使用(データ保持)。旧 queue の子 process 記録。"""

    __tablename__ = "execution_child"
    id: Mapped[str] = mapped_column(Text, primary_key=True)
    attempt_id: Mapped[str] = mapped_column(Text, ForeignKey("execution_attempt.id"))
    namespace: Mapped[str] = mapped_column(Text)
    message_id: Mapped[str] = mapped_column(Text)
    targets: Mapped[list[str]] = mapped_column(JSONB)
    pid: Mapped[int | None] = mapped_column(Integer)
    birth_time: Mapped[float | None] = mapped_column(Double)
    state: Mapped[str] = mapped_column(Text, server_default=text("'starting'"))
    __table_args__ = (Index("idx_execution_child_unfinished", "namespace", "state"),)


class ExecutionLog(Base):
    """``logs`` — 実行ログの追記専用行。id は移行が元 id を保持するため
    ``GENERATED BY DEFAULT AS IDENTITY``。"""

    __tablename__ = "logs"
    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True)
    event_type: Mapped[str] = mapped_column(Text)
    run_id: Mapped[str] = mapped_column(Text)
    execution_id: Mapped[str] = mapped_column(Text, unique=True)
    parent_execution_id: Mapped[str | None] = mapped_column(Text)
    component: Mapped[str] = mapped_column(Text)
    started_at: Mapped[str] = mapped_column(Text)
    duration_ms: Mapped[int] = mapped_column(BigInteger)
    status: Mapped[str] = mapped_column(Text)
    request_json: Mapped[str] = mapped_column(Text)
    result_json: Mapped[str | None] = mapped_column(Text)
    error_json: Mapped[str | None] = mapped_column(Text)
    usage_json: Mapped[str | None] = mapped_column(Text)
    cost_usd: Mapped[str | None] = mapped_column(Text)
    # 記録した process の実行版(``core/builtin/code_version``)。旧行は NULL。
    code_version: Mapped[str | None] = mapped_column(Text)
    __table_args__ = (
        Index("idx_logs_run", "run_id", "id"),
        Index("idx_logs_parent", "parent_execution_id"),
        Index("idx_logs_type", "event_type", "started_at"),
    )


class Memory(Base):
    """``memory`` — Tool が保存する比較 baseline などの key-value 記録。"""

    __tablename__ = "memory"
    identity: Mapped[str] = mapped_column(Text, primary_key=True)
    value: Mapped[str] = mapped_column(Text)
    saved_at: Mapped[str] = mapped_column(Text)


class WorkspaceSlot(Base):
    """``workspace_slot`` — 常駑 clone 棚の状態表(grow-only、行は削除しない)。"""

    __tablename__ = "workspace_slot"
    id: Mapped[str] = mapped_column(Text, primary_key=True)
    owner_repo: Mapped[str] = mapped_column(Text)
    slot_no: Mapped[int] = mapped_column(Integer)
    pr_number: Mapped[int | None] = mapped_column(Integer)
    branch: Mapped[str | None] = mapped_column(Text)
    state: Mapped[bool] = mapped_column(Boolean, server_default=text("FALSE"))
    holder: Mapped[str | None] = mapped_column(Text)
    acquired_at: Mapped[float | None] = mapped_column(Double)
    checked_at: Mapped[float | None] = mapped_column(Double)
    created_at: Mapped[float] = mapped_column(Double)
    updated_at: Mapped[float] = mapped_column(Double)
    lease_id: Mapped[str | None] = mapped_column(Text)
    owner_pid: Mapped[int | None] = mapped_column(Integer)
    owner_process: Mapped[str | None] = mapped_column(Text)
    unbind_requested: Mapped[bool] = mapped_column(Boolean, server_default=text("FALSE"))
    #: busy の間に棟が扱う PR の head。同じ PR・head の取得を排他する。idle・PR 外の取得は NULL。
    head_sha: Mapped[str | None] = mapped_column(Text)
    __table_args__ = (UniqueConstraint("owner_repo", "slot_no"),)


class Session(Base):
    """``session`` — 会話 session。任意 string 主キーと自己参照 parent。"""

    __tablename__ = "session"
    session_id: Mapped[str] = mapped_column(Text, primary_key=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=text("CURRENT_TIMESTAMP")
    )
    parent_session_id: Mapped[str | None] = mapped_column(
        Text, ForeignKey("session.session_id")
    )


class SessionRun(Base):
    """``session_run`` — session に紐く実行記録。status は状態機械の全種別。"""

    __tablename__ = "session_run"
    run_id: Mapped[str] = mapped_column(Text, primary_key=True)
    session_id: Mapped[str] = mapped_column(Text, ForeignKey("session.session_id"))
    agent_name: Mapped[str] = mapped_column(Text)
    data_json: Mapped[dict[str, Any]] = mapped_column(JSONB)
    request_json: Mapped[Any] = mapped_column(JSONB)
    status: Mapped[str] = mapped_column(Text, server_default=text("'running'"))
    response_json: Mapped[Any | None] = mapped_column(JSONB)
    started_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=text("CURRENT_TIMESTAMP")
    )
    finished_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    # run を挿入した process の実行版。完了・中断回復では変えない。旧行は NULL。
    code_version: Mapped[str | None] = mapped_column(Text)
    __table_args__ = (
        # cancelled は期限による取消し、interrupted は前プロセスの停止で終わらなかった run。
        # skipped は書かない。配備中に動く旧版の書込みとの互換のため、次の release まで許可する。
        CheckConstraint(
            "status IN ('running', 'ok', 'error', 'max_steps', 'skipped', 'cancelled', 'interrupted')",
            name="session_run_status_check",
        ),
        Index("idx_session_run_session", "session_id", "started_at", "run_id"),
    )


class DiscordMessage(Base):
    """``discord_message`` — bot が送った Discord メッセージ(分割の各 chunk)と、送った run・Agent 実行。

    部品の配送(``tools/discord/deliver``)が送信の後に書く。``delivery_id`` は一回の配送の分割をまとめる。
    run の外の送信は run_id・execution_id が NULL。評価(``run_feedback``)が送り元の run をここから引く。
    """

    __tablename__ = "discord_message"
    message_id: Mapped[str] = mapped_column(Text, primary_key=True)
    channel_id: Mapped[str] = mapped_column(Text)
    delivery_id: Mapped[str] = mapped_column(Text)
    run_id: Mapped[str | None] = mapped_column(Text)
    execution_id: Mapped[str | None] = mapped_column(Text)
    sent_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=text("CURRENT_TIMESTAMP")
    )
    __table_args__ = (Index("idx_discord_message_run", "run_id"),)


class RunFeedback(Base):
    """``run_feedback`` — 本人が bot の Discord メッセージに付けた 👍/👎。評価したメッセージごとに 1 行。

    rating は ``up``・``down``。run・session・Agent 実行は評価時に ``discord_message`` と ``session_run`` から写す。
    👎 には追問(question_message_id)を送り、その追問への本人の返信を ``reasons`` に順に足す
    (``{"message_id", "text", "at"}`` の配列)。評価が変わると追問と原因を消し、取り消すと行を消す。
    session の評価はその run の行の集計で、別の行を持たない。
    """

    __tablename__ = "run_feedback"
    message_id: Mapped[str] = mapped_column(Text, primary_key=True)
    channel_id: Mapped[str] = mapped_column(Text)
    run_id: Mapped[str] = mapped_column(Text)
    session_id: Mapped[str] = mapped_column(Text)
    execution_id: Mapped[str | None] = mapped_column(Text)
    rating: Mapped[str] = mapped_column(Text)
    rated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=text("CURRENT_TIMESTAMP")
    )
    question_message_id: Mapped[str | None] = mapped_column(Text, unique=True)
    reasons: Mapped[list[dict[str, Any]]] = mapped_column(JSONB, server_default=text("'[]'::jsonb"))
    __table_args__ = (
        CheckConstraint("rating IN ('up', 'down')", name="run_feedback_rating_check"),
        Index("idx_run_feedback_run", "run_id"),
        Index("idx_run_feedback_session", "session_id"),
    )


class Channel(Base):
    """``channel`` — provider x channel_id ごとの session 対応表。"""

    __tablename__ = "channel"
    provider: Mapped[str] = mapped_column(Text, primary_key=True)
    channel_id: Mapped[str] = mapped_column(Text, primary_key=True)
    session_id: Mapped[str] = mapped_column(Text)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=text("CURRENT_TIMESTAMP")
    )


class ProjectChannel(Base):
    """``project_channel`` — project ごとの播報先 channel 対応表。

    project は非空の自由ラベル(原文)。channel_id は一意とし、
    1 channel を 1 project の播報板として管理する。
    """

    __tablename__ = "project_channel"
    project: Mapped[str] = mapped_column(Text, primary_key=True)
    channel_id: Mapped[str] = mapped_column(Text, unique=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=text("CURRENT_TIMESTAMP")
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=text("CURRENT_TIMESTAMP")
    )


