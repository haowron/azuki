"""Append-only execution log on PostgreSQL (``config.DATABASE_URL``).

The sink satisfies the :class:`~trackeverything.core.abc.execution_log.LogRecorder`
protocol; the composition root picks it through
:func:`~trackeverything.core.builtin.database.open_execution_logger`. Recording
must never change execution: the sink swallows its own failures and only logs
them. Rows go through the ORM model in
:mod:`~trackeverything.core.orm` — no SQL strings here.
"""

from __future__ import annotations

import json
import logging
from dataclasses import dataclass
from typing import Any

from sqlalchemy import Boolean, Text, and_, case, cast, func, insert, literal, select
from sqlalchemy.dialects.postgresql import JSONB, JSONPATH
from sqlalchemy.ext.asyncio import AsyncSession

from trackeverything.core.builtin.code_version import current_code_version
from trackeverything.core.builtin.domain.execution_log import LogEvent
from trackeverything.core.orm import ExecutionLog as ExecutionLogRow
from trackeverything.core.orm import Session as SessionRow
from trackeverything.core.orm import SessionRun as SessionRunRow
from trackeverything.core.orm import sessions_for

log = logging.getLogger(__name__)


class PostgresExecutionLogger:
    """Persist complete execution events to the shared PostgreSQL database.

    Connection policy: one shared engine (URL-cached, pool_pre_ping) with one
    short session per record — the connect cost is negligible next to the
    agent and LLM turns an event records. Failures are logged and swallowed —
    observability must not change source, agent, or LLM behavior. ``id`` is
    ``GENERATED BY DEFAULT AS IDENTITY`` so the SQLite→PostgreSQL migration
    could carry the original ids and the identity sequence resumes after them.
    """

    def __init__(self, dsn: str) -> None:
        if not dsn.strip():
            raise ValueError("execution logging requires PostgreSQL DATABASE_URL")
        self._dsn = dsn
        self._sessions = sessions_for(dsn)

    async def record(self, event: LogEvent) -> None:
        """Append one event; never raise — a log write must not fail a run.

        Every row carries this process's code version, so each event can be
        traced to the version that produced it. Stamping here covers every
        logger instance, including the ones tools open on their own.
        """
        try:
            async with self._sessions() as session:
                await session.execute(
                    insert(ExecutionLogRow).values(
                        event_type=event.event_type,
                        run_id=event.run_id,
                        execution_id=event.execution_id,
                        parent_execution_id=event.parent_execution_id,
                        component=event.component,
                        started_at=event.started_at,
                        duration_ms=event.duration_ms,
                        status=event.status,
                        request_json=_dump(event.request),
                        result_json=_dump_optional(event.result),
                        error_json=_dump_optional(event.error),
                        usage_json=_dump_optional(event.usage),
                        cost_usd=event.cost_usd,
                        code_version=current_code_version(),
                    )
                )
                await session.commit()
        except Exception:
            # Observability must not change source, agent, or LLM behavior.
            log.exception("failed to persist %s log event", event.event_type)


def _dump(value: Any) -> str:
    return json.dumps(value, default=str, ensure_ascii=False)


def _dump_optional(value: Any) -> str | None:
    return None if value is None else _dump(value)


@dataclass(frozen=True)
class ComponentUsage:
    """Invocation counts of one component name (agent or tool)."""

    component: str
    total: int
    by_status: dict[str, int]
    last_used_at: str | None


@dataclass(frozen=True)
class UsageSummary:
    """Agent / tool invocation counts aggregated from the ``logs`` table."""

    agents: list[ComponentUsage]
    tools: list[ComponentUsage]
    agents_since: str | None
    tools_since: str | None


async def read_usage(dsn: str) -> UsageSummary:
    """Group ``agent`` / ``tool`` events per component name with status counts.

    Read path of the usage statistics screen: a plain ORM aggregation (no SQL
    strings) over the same ``logs`` rows the logger appends. Statuses come
    back as a per-component counter map so callers decide which statuses to
    surface. Rows sort by total desc, then name; ``since`` is the earliest
    ``started_at`` of each event type so the screen can state its range.
    """
    if not dsn.strip():
        raise ValueError("usage aggregation requires PostgreSQL DATABASE_URL")

    async def collect(session: AsyncSession, event_type: str) -> tuple[list[ComponentUsage], str | None]:
        rows = (
            await session.execute(
            select(
                ExecutionLogRow.component,
                ExecutionLogRow.status,
                func.count(),
                func.max(ExecutionLogRow.started_at),
                func.min(ExecutionLogRow.started_at),
            )
                .where(ExecutionLogRow.event_type == event_type)
                .group_by(ExecutionLogRow.component, ExecutionLogRow.status)
            )
        ).all()
        by_component: dict[str, dict[str, Any]] = {}
        since: str | None = None
        for component, status, calls, last_used_at, first_used_at in rows:
            entry = by_component.setdefault(component, {"total": 0, "by_status": {}, "last": None})
            entry["total"] += int(calls)
            entry["by_status"][status] = entry["by_status"].get(status, 0) + int(calls)
            if last_used_at and (entry["last"] is None or last_used_at > entry["last"]):
                entry["last"] = last_used_at
            if first_used_at and (since is None or first_used_at < since):
                since = first_used_at
        items = [
            ComponentUsage(component=component, total=data["total"], by_status=data["by_status"], last_used_at=data["last"])
            for component, data in by_component.items()
        ]
        items.sort(key=lambda item: (-item.total, item.component))
        return items, since

    async with sessions_for(dsn)() as session:
        agents, agents_since = await collect(session, "agent")
        tools, tools_since = await collect(session, "tool")
    return UsageSummary(agents=agents, tools=tools, agents_since=agents_since, tools_since=tools_since)


# ---- 実行フロー(run・session の可視化)の読取り ---------------------------------

# 画面の抜粋は 300 文字まで。切り詰めの有無を判定できるよう 1 文字多く読む。
PREVIEW_LIMIT = 300
_HEAD = PREVIEW_LIMIT + 1


@dataclass(frozen=True)
class RunEvent:
    """One ``logs`` row of a run, reduced to what the run-flow screen reads.

    ``request_head`` は Tool の引数、``result_head`` は Agent の応答本文・LLM の
    最終文・Harness / CLI の結果 JSON の先頭、``calls`` は LLM が選んだ
    Tool 名。LLM と Agent の request(prompt・会話・Context)は読まない。
    一覧用の軽い読取りでは JSON 由来の欄を None のままにする。
    """

    event_type: str
    execution_id: str
    parent_execution_id: str | None
    component: str
    started_at: str
    duration_ms: int
    status: str
    cost_usd: str | None = None
    usage_json: str | None = None
    error_json: str | None = None
    request_head: str | None = None
    result_head: str | None = None
    calls: tuple[str, ...] | None = None
    log_id: int = 0


@dataclass(frozen=True)
class RunRecord:
    """The light columns of one ``session_run`` row (no input / response bodies)."""

    run_id: str
    session_id: str
    agent_name: str
    status: str
    started_at: str
    finished_at: str | None


@dataclass(frozen=True)
class RunTrace:
    """Logged events of one run plus its session record when the run has one."""

    run_id: str
    events: list[RunEvent]
    record: RunRecord | None


@dataclass(frozen=True)
class SessionTrace:
    """One session with its latest runs in start order and the total run count."""

    session_id: str
    parent_session_id: str | None
    created_at: str
    total_runs: int
    runs: list[RunTrace]


_LIGHT_COLUMNS = (
    ExecutionLogRow.id,
    ExecutionLogRow.run_id,
    ExecutionLogRow.event_type,
    ExecutionLogRow.execution_id,
    ExecutionLogRow.parent_execution_id,
    ExecutionLogRow.component,
    ExecutionLogRow.started_at,
    ExecutionLogRow.duration_ms,
    ExecutionLogRow.status,
    ExecutionLogRow.cost_usd,
)
_RECORD_COLUMNS = (
    SessionRunRow.run_id,
    SessionRunRow.session_id,
    SessionRunRow.agent_name,
    SessionRunRow.status,
    SessionRunRow.started_at,
    SessionRunRow.finished_at,
)


def _detail_columns() -> tuple[Any, ...]:
    """Light columns plus the bounded previews; LLM / Agent requests stay unread."""
    kind = ExecutionLogRow.event_type
    result = ExecutionLogRow.result_json
    # 不正な JSON の行が 1 件あっても run 全体の照会を失敗させない。
    parsable = func.pg_input_is_valid(result, literal("jsonb"), type_=Boolean)
    document = cast(result, JSONB)
    request_head = case((kind == "tool", func.substr(ExecutionLogRow.request_json, 1, _HEAD)), else_=None)
    result_head = case(
        (and_(kind == "agent", parsable), func.substr(document["response"].astext, 1, _HEAD)),
        (and_(kind == "llm", parsable), func.substr(document["text"].astext, 1, _HEAD)),
        (kind.in_(("harness", "cli")), func.substr(result, 1, _HEAD)),
        else_=None,
    ).cast(Text)
    calls = case(
        (and_(kind == "llm", parsable), func.jsonb_path_query_array(document, cast(literal("$.calls[*].name"), JSONPATH), type_=JSONB)),
        else_=None,
    )
    return (
        *_LIGHT_COLUMNS,
        ExecutionLogRow.usage_json,
        ExecutionLogRow.error_json,
        request_head.label("request_head"),
        result_head.label("result_head"),
        calls.label("calls"),
    )


def _iso(value: Any) -> str:
    return value.isoformat() if hasattr(value, "isoformat") else str(value)


def _event(row: Any, *, detail: bool) -> RunEvent:
    names = row.calls if detail else None
    return RunEvent(
        event_type=row.event_type,
        execution_id=row.execution_id,
        parent_execution_id=row.parent_execution_id,
        component=row.component,
        started_at=row.started_at,
        duration_ms=int(row.duration_ms),
        status=row.status,
        cost_usd=row.cost_usd,
        usage_json=row.usage_json if detail else None,
        error_json=row.error_json if detail else None,
        request_head=row.request_head if detail else None,
        result_head=row.result_head if detail else None,
        calls=tuple(str(name) for name in names) if isinstance(names, list) and names else None,
        log_id=int(row.id),
    )


def _record(row: Any) -> RunRecord:
    return RunRecord(
        run_id=row.run_id,
        session_id=row.session_id,
        agent_name=row.agent_name,
        status=row.status,
        started_at=_iso(row.started_at),
        finished_at=None if row.finished_at is None else _iso(row.finished_at),
    )


async def _light_traces(session: AsyncSession, run_ids: list[str]) -> dict[str, RunTrace]:
    """Light events and session records of several runs, keyed by run id."""
    if not run_ids:
        return {}
    events: dict[str, list[RunEvent]] = {run_id: [] for run_id in run_ids}
    rows = (
        await session.execute(
            select(*_LIGHT_COLUMNS)
            .where(ExecutionLogRow.run_id.in_(run_ids))
            .order_by(ExecutionLogRow.started_at, ExecutionLogRow.id)
        )
    ).all()
    for row in rows:
        events[row.run_id].append(_event(row, detail=False))
    records = {
        row.run_id: _record(row)
        for row in (await session.execute(select(*_RECORD_COLUMNS).where(SessionRunRow.run_id.in_(run_ids)))).all()
    }
    return {run_id: RunTrace(run_id=run_id, events=events[run_id], record=records.get(run_id)) for run_id in run_ids}


def _require_dsn(dsn: str) -> None:
    if not dsn.strip():
        raise ValueError("run flow requires PostgreSQL DATABASE_URL")


async def read_run_trace(dsn: str, run_id: str, *, limit: int) -> RunTrace | None:
    """Events of one run in start order (at most ``limit``) and its session record.

    Returns None when neither ``logs`` nor ``session_run`` knows the run id.
    """
    _require_dsn(dsn)
    async with sessions_for(dsn)() as session:
        rows = (
            await session.execute(
                select(*_detail_columns())
                .where(ExecutionLogRow.run_id == run_id)
                .order_by(ExecutionLogRow.started_at, ExecutionLogRow.id)
                .limit(limit)
            )
        ).all()
        found = (await session.execute(select(*_RECORD_COLUMNS).where(SessionRunRow.run_id == run_id))).first()
    if not rows and found is None:
        return None
    return RunTrace(
        run_id=run_id,
        events=[_event(row, detail=True) for row in rows],
        record=None if found is None else _record(found),
    )


async def read_session_trace(dsn: str, session_id: str, *, limit: int) -> SessionTrace | None:
    """A session with its latest ``limit`` runs (start order) and light run events.

    Returns None when the session id is unknown.
    """
    _require_dsn(dsn)
    async with sessions_for(dsn)() as session:
        found = (
            await session.execute(
                select(SessionRow.session_id, SessionRow.created_at, SessionRow.parent_session_id).where(
                    SessionRow.session_id == session_id
                )
            )
        ).first()
        if found is None:
            return None
        total = await session.scalar(
            select(func.count()).select_from(SessionRunRow).where(SessionRunRow.session_id == session_id)
        )
        latest = (
            await session.execute(
                select(SessionRunRow.run_id)
                .where(SessionRunRow.session_id == session_id)
                .order_by(SessionRunRow.started_at.desc(), SessionRunRow.run_id.desc())
                .limit(limit)
            )
        ).scalars().all()
        run_ids = list(reversed(latest))
        traces = await _light_traces(session, run_ids)
    return SessionTrace(
        session_id=found.session_id,
        parent_session_id=found.parent_session_id,
        created_at=_iso(found.created_at),
        total_runs=int(total or 0),
        runs=[traces[run_id] for run_id in run_ids],
    )


async def read_recent_runs(dsn: str, *, limit: int) -> list[RunTrace]:
    """The ``limit`` runs with the latest log activity, newest first (light events)."""
    _require_dsn(dsn)
    last = func.max(ExecutionLogRow.id).label("last_id")
    async with sessions_for(dsn)() as session:
        run_ids = list(
            (
                await session.execute(
                    select(ExecutionLogRow.run_id, last).group_by(ExecutionLogRow.run_id).order_by(last.desc()).limit(limit)
                )
            ).scalars()
        )
        traces = await _light_traces(session, run_ids)
    return [traces[run_id] for run_id in run_ids]
